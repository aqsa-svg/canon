pytestmark = pytest.mark.data

GoldRows = tuple[tuple[Scalar, ...], ...]


class Case(BaseModel):
    """One compiler case. A frozen model rather than a tuple, per CLAUDE.md."""

    model_config = ConfigDict(frozen=True, arbitrary_types_allowed=True)

    name: str
    intent: QueryIntent
    gold_sql: str
    gold_rows: GoldRows
    note: str = ""


def _year(year: int) -> TimeRange:
    """A whole calendar year as a half-open range."""
    return TimeRange(start=f"{year}-01-01", end=f"{year + 1}-01-01")



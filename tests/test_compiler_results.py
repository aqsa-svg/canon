def _normalise(rows: object) -> GoldRows:
    """Compare timestamps as ISO strings so a gold literal stays readable in the file."""
    normalised: list[tuple[Scalar, ...]] = []
    for row in rows:  # type: ignore[union-attr]
        cells: list[Scalar] = []
        for cell in row:
            cells.append(str(cell) if hasattr(cell, "isoformat") else cell)
        normalised.append(tuple(cells))
    return tuple(normalised)


def _assert_rows_equal(actual: GoldRows, expected: GoldRows, label: str) -> None:
    assert len(actual) == len(expected), f"{label}: {len(actual)} rows, expected {len(expected)}"
    for index, (actual_row, expected_row) in enumerate(zip(actual, expected, strict=True)):
        assert len(actual_row) == len(expected_row), f"{label}: row {index} width differs"
        for actual_cell, expected_cell in zip(actual_row, expected_row, strict=True):
            if isinstance(expected_cell, Decimal):
                # Money is compared as DECIMAL, exactly, per docs/01-evaluation.md.
                assert actual_cell == expected_cell, f"{label}: row {index}"
            elif isinstance(expected_cell, float):
                assert actual_cell == pytest.approx(expected_cell, rel=1e-9), (
                    f"{label}: row {index}"
                )
            else:
                assert actual_cell == expected_cell, f"{label}: row {index}"


@pytest.mark.parametrize("case", CASES, ids=[case.name for case in CASES])
def test_compiled_sql_returns_the_gold_value(
    case: Case, layer: SemanticLayer, warehouse: duckdb.DuckDBPyConnection
) -> None:
    """The compiler's SQL must return the committed gold value."""
    compiled = compile_intent(case.intent, layer)
    actual = _normalise(warehouse.execute(compiled.sql).fetchall())
    _assert_rows_equal(actual, case.gold_rows, f"{case.name} (compiled vs gold value)")


@pytest.mark.parametrize("case", CASES, ids=[case.name for case in CASES])
def test_compiled_sql_agrees_with_hand_written_gold_sql(
    case: Case, layer: SemanticLayer, warehouse: duckdb.DuckDBPyConnection
) -> None:
    """The compiler's SQL and the hand-written SQL must agree with each other.

    Catches the case where the gold literal was committed from a wrong query: two
    independently written queries agreeing on the same number is much stronger evidence
    than either one alone.
    """
    compiled = compile_intent(case.intent, layer)
    from_compiler = _normalise(warehouse.execute(compiled.sql).fetchall())
    from_gold = _normalise(warehouse.execute(case.gold_sql).fetchall())
    _assert_rows_equal(from_compiler, from_gold, f"{case.name} (compiled vs gold SQL)")


@pytest.mark.parametrize("case", CASES, ids=[case.name for case in CASES])
def test_every_case_carries_its_metric_card_and_caveats(case: Case, layer: SemanticLayer) -> None:
    """A number never travels without its definition.

    The metric card and its caveats are part of the compiler's output, not something the
    presentation layer is trusted to remember to attach.
    """
    compiled = compile_intent(case.intent, layer)
    assert compiled.metric.name == str(case.intent.metric)
    assert compiled.metric.description
    assert compiled.metric.owner
    card_caveats = [c for c in compiled.caveats if c.source.value == "from_metric_card"]
    assert len(card_caveats) == len(compiled.metric.caveats)

"""Thirteen hand-written cases: intent in, verified number out.

Each case carries two independent references:

* ``gold_sql`` -- written by hand from the metric card, with its own aliases and its
  own join style. Not generated, not derived from the compiler.
* ``gold_value`` -- the value that gold SQL returned when run against
  data/canon.duckdb, committed as a literal.

Both matter. Comparing only against gold SQL would pass if a mistake were made in both
places the same way; comparing only against the literal would not survive a data
reload. Together, a compiler bug, a gold error, and a data change are all distinguishable.

Per docs/01-evaluation.md, gold SQL is written by a human reading the definition -- never
generated by a model. No LLM is involved in this file.
"""

from __future__ import annotations

